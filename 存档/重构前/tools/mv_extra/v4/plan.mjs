export const SHOTS = RAW_SHOTS.map((s, idx) => {
  const start = s.f0 / FPS;
  const end = s.f1 / FPS;
  const actObj = ACTS.find((a) => a.id === s.act);
  const beatIndex = (start - TEMPO.beat0) / TEMPO.spb;
  const bar = Math.max(0, Math.floor(beatIndex / 4));
  const beatInBar = (((beatIndex % 4) + 4) % 4) + 1;

  return {
    ...s,
    index: idx + 1,
    start,
    end,
    duration: end - start,
    barBeat: `${bar}:${beatInBar.toFixed(1).replace(/\.0$/, '')}`,
    grade: actObj.grade,
    direction: {
      moment: s.moment,
      focus: s.focus,
      layout: s.layout,
      action: s.action,
      trigger: s.trigger,
      result: s.result,
      holdSeconds: +(end - s.result).toFixed(3),
      entry: idx === 0 ? 'audio 0.000s' : RAW_SHOTS[idx - 1].id,
      exit: idx + 1 < RAW_SHOTS.length ? RAW_SHOTS[idx + 1].id : 'audio tail 56.033s',
    },
  };
});

export function shotAtFrame(frameIdx) {
  const f = Math.max(0, Math.min(TOTAL_FRAMES - 1, frameIdx));
  return SHOTS.find((s) => f >= s.f0 && f < s.f1);
}

export function shotAtTime(t) {
  const f = Math.max(0, Math.min(TOTAL_FRAMES - 1, Math.floor(t * FPS + 1e-6)));
  return shotAtFrame(f);
}
