#!/usr/bin/env python3
"""Bake walk-v14's aligned 8-frame atlases into Tonghuazhen's indexed sprites.

The MV renderer has no runtime PNG decoder. Each fixed 384x416 cell is cropped
at the shared ground line, scaled to its established character height, quantized
to px.js's palette, then RLE-baked for the browser renderer.
"""
from __future__ import annotations

import base64
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
MV = ROOT / "番外MV" / "童话镇"
ATLAS_ROOT = ROOT / "assets" / "ai-girls" / "walk-v14"
OUT = MV / "src" / "walk_cycle_data.js"
CELL_W = 384
CROP_TOP = 32
CROP_BOTTOM = 407
CROP_H = CROP_BOTTOM - CROP_TOP
TRANSPARENT = 255
RLE = 254

# Preserve each actor's established high-resolution sprite height. The map
# avatar and Red Hood close-up get separately scaled data from the same atlas.
ATLAS_BY_ACTOR = {
    "whale": ("whale_walk_side_2leg", 88),
    "doubao": ("doubao_walk_side_2leg", 64),
    "gemini": ("gemini_walk_2leg", 84),
    "claude": ("claude_walk_2leg", 90),
    "kimi": ("kimi_walk_2leg", 84),
    "qwen": ("qwen_walk_2leg", 84),
    "zai": ("zai_walk_2leg", 84),
}


def hex_rgb(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    return tuple(int(value[i : i + 2], 16) for i in (0, 2, 4))


def read_palette() -> list[str]:
    px = (MV / "src" / "px.js").read_text(encoding="utf-8")
    literal = px.split("const HEX = [", 1)[1].split("];", 1)[0]
    base = re.findall(r"['\"](#[0-9a-fA-F]{6})['\"]", literal.split("...CHAR_HEX", 1)[0])
    assert len(base) == 48, f"Expected the 48 engine palette colors, got {len(base)}"

    sprites = (MV / "src" / "sprites_data.js").read_text(encoding="utf-8")
    match = re.search(r"export const CHAR_HEX = (\[.*?\]);", sprites, re.S)
    assert match, "Could not read CHAR_HEX from sprites_data.js"
    palette = base + json.loads(match.group(1))
    assert len(palette) < RLE, "Palette indices must not collide with the RLE marker"
    return palette


def encode_rle(raw: bytes) -> str:
    """Match getBakedSprite's [254, run, value] RLE format."""
    out = bytearray()
    i = 0
    while i < len(raw):
        value = raw[i]
        j = i + 1
        while j < len(raw) and raw[j] == value and j - i < 255:
            j += 1
        run = j - i
        if run >= 3:
            out.extend((RLE, run, value))
        else:
            out.extend(raw[i:j])
        i = j
    return base64.b64encode(out).decode("ascii")


def bake_atlas(atlas_name: str, prefix: str, target_h: int, palette: Image.Image) -> list[tuple[str, int, int, str]]:
    atlas_path = ATLAS_ROOT / f"{atlas_name}.png"
    atlas = Image.open(atlas_path).convert("RGBA")
    assert atlas.size == (CELL_W * 8, 416), f"Unexpected atlas size: {atlas_path} {atlas.size}"
    target_w = round(CELL_W * target_h / CROP_H)
    records = []
    for frame in range(8):
        cell = atlas.crop((frame * CELL_W, CROP_TOP, (frame + 1) * CELL_W, CROP_BOTTOM))
        scaled = cell.resize((target_w, target_h), Image.Resampling.LANCZOS)
        alpha = scaled.getchannel("A").tobytes()
        quantized = scaled.convert("RGB").quantize(palette=palette, dither=Image.Dither.NONE)
        indices = bytearray(quantized.tobytes())
        for i, opacity in enumerate(alpha):
            if opacity < 128:
                indices[i] = TRANSPARENT
        records.append((f"{prefix}_{frame}", target_w, target_h, encode_rle(bytes(indices))))
    return records


def main() -> None:
    palette_hex = read_palette()
    palette_rgb = [component for value in palette_hex for component in hex_rgb(value)]
    palette_rgb.extend(palette_rgb[:3] * (256 - len(palette_hex)))
    palette = Image.new("P", (1, 1))
    palette.putpalette(palette_rgb)

    records = []
    for actor, (atlas_name, target_h) in ATLAS_BY_ACTOR.items():
        records.extend(bake_atlas(atlas_name, f"walk_{actor}", target_h, palette))
    records.extend(bake_atlas("whale_walk_side_2leg", "walk_map_whale", 56, palette))
    records.extend(bake_atlas("doubao_walk_side_2leg", "walk_doubao_big", 84, palette))

    lines = [
        "// Generated by tools/remotion-engine/bake_tonghuazhen_walk_cycles.py; do not hand-edit.",
        "import { RAW_SPRITES, getBakedSprite } from './sprites_data.js';",
        "",
        "Object.assign(RAW_SPRITES, {",
    ]
    for key, width, height, data in records:
        lines.append(f"  {key}: [{width}, {height}, '{data}'],")
    lines += [
        "});",
        "",
        "export const WALK_CYCLE_FPS = 1000 / 120;",
        "export const WALK_CYCLE_FRAMES = 8;",
        "",
        "export function getWalkCycleFrame(time) {",
        "  const phase = Math.floor(time * WALK_CYCLE_FPS);",
        "  return ((phase % WALK_CYCLE_FRAMES) + WALK_CYCLE_FRAMES) % WALK_CYCLE_FRAMES;",
        "}",
        "",
        "export function getWalkCycleBob(frame) {",
        "  const phase = ((Math.trunc(frame) % WALK_CYCLE_FRAMES) + WALK_CYCLE_FRAMES) % WALK_CYCLE_FRAMES;",
        "  return phase === 2 || phase === 6 ? -1 : 0;",
        "}",
        "",
        "export function getWalkCycleSprite(actor, frame, big = false) {",
        "  const index = ((Math.trunc(frame) % WALK_CYCLE_FRAMES) + WALK_CYCLE_FRAMES) % WALK_CYCLE_FRAMES;",
        "  const key = actor === 'doubao' && big ? `walk_doubao_big_${index}` : `walk_${actor}_${index}`;",
        "  return getBakedSprite(key);",
        "}",
        "",
    ]
    OUT.write_text(chr(10).join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(records)} frames, {OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
